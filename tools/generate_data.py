def recipes():
    R = D / "recipe"

    def shaped(name, pattern, key, result, count=1):
        w(R / f"{name}.json", {"type": "minecraft:crafting_shaped", "category": "misc", "pattern": pattern,
                               "key": {k: ({"tag": v[1:]} if v.startswith("#") else {"item": v}) for k, v in key.items()},
                               "result": {"id": result, "count": count}})

    def shapeless(name, ingredients, result, count=1, conditions=None):
        r = {"type": "minecraft:crafting_shapeless", "category": "misc",
             "ingredients": [({"tag": v[1:]} if v.startswith("#") else {"item": v}) for v in ingredients],
             "result": {"id": result, "count": count}}
        if conditions:
            r = {"neoforge:conditions": conditions, **r}
        w(R / f"{name}.json", r)

    shaped("telescope", [" CS", " C ", "/ /"], {"C": "minecraft:copper_ingot", "S": "minecraft:spyglass",
                                               "/": "minecraft:stick"}, f"{M}:telescope")
    shapeless("star_atlas", ["minecraft:book", "minecraft:glow_ink_sac"], f"{M}:star_atlas")
    # 0.6.0: shards come from finds (1 per bright constellation), so the lens takes four
    shaped("star_lens", [" S ", "SPS", " S "], {"P": "minecraft:glass_pane", "S": f"{M}:star_shard"}, f"{M}:star_lens")
    shaped("nebula_filter", ["DLD", "LSL", "DLD"], {"D": f"{M}:stardust", "L": "minecraft:lapis_lazuli",
                                                  "S": f"{M}:star_shard"}, f"{M}:nebula_filter")
    # stardust from shards, starstone from stone and stardust
    shapeless("stardust", [f"{M}:star_shard"], f"{M}:stardust", 4)
    shaped("starstone", ["CCC", "CDC", "CCC"], {"C": "#minecraft:stone_crafting_materials", "D": f"{M}:stardust"},
           f"{M}:starstone", 8)
    shaped("starstone_bricks", ["SS", "SS"], {"S": f"{M}:starstone"}, f"{M}:starstone_bricks", 4)
    shaped("star_lamp", ["BGB", "GSG", "BGB"], {"B": f"{M}:starstone_bricks", "G": "minecraft:glass",
                                              "S": f"{M}:star_shard"}, f"{M}:star_lamp", 4)
    shaped("nebula_glass", ["GGG", "GDG", "GGG"], {"G": "minecraft:glass", "D": f"{M}:stardust"}, f"{M}:nebula_glass", 8)
    # 1.1.0: the big pieces, from the six planet lamps (one each, for tracking) and a Star Lamp
    if PIECES:                     # set aside for now (WSRegistry.PIECES)
        lamps = {"E": f"{M}:ember_lamp", "V": f"{M}:verdigris_lamp", "G": f"{M}:old_gold_lamp", "P": f"{M}:pale_rider_lamp",
                 "I": f"{M}:indigo_lamp", "C": f"{M}:cinder_lamp", "S": f"{M}:star_lamp"}
        shaped("grand_orrery", ["EVG", "PSI", "COW"], {**lamps, "O": f"{M}:orrery", "W": "minecraft:dark_oak_planks"},
               f"{M}:grand_orrery")
        shaped("planet_mobile", ["EHV", "GSP", "ITC"], {**lamps, "H": "minecraft:chain", "T": "minecraft:string"},
               f"{M}:planet_mobile")


