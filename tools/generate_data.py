def forgotten_blocks():
    """The weather blocks (GeckoLib: the block model only gives breaking particles), the North Star Lodestone (a plain
    cube_bottom_top) and Sky Window glass (drawn by its block entity renderer; the model gives particles only). Their
    items have no crafting-table recipe: they are made from the open Star Atlas (atlas/Recipes.java)."""
    for bid in GECKO:
        w(A / f"models/block/{bid}.json", {"textures": {"particle": f"{M}:item/{bid}"}})
        w(A / f"models/item/{bid}.json", {"parent": "minecraft:item/generated", "textures": {"layer0": f"{M}:item/{bid}"}})
        loot_self(bid)
    for bid in ("cloudbuster", "storm_jar"):
        w(A / f"blockstates/{bid}.json", {"variants": {f"facing={f},powered={p}": {"model": f"{M}:block/{bid}"}
                                                      for f in FACINGS for p in ("false", "true")}})
    w(A / "blockstates/orrery.json", {"variants": {f"facing={f},up={u},weather={k}": {"model": f"{M}:block/orrery"}
                                                   for f in FACINGS for u in ("false", "true") for k in range(4)}})
    # 1.1.0: GeckoLib (models/north_star_lodestone, tools/lodestone/lodestone_model.py); the block model gives particles
    w(A / "models/block/north_star_lodestone.json", {"textures": {"particle": f"{M}:block/north_star_lodestone_side"}})
    w(A / "blockstates/north_star_lodestone.json", {"variants": {"": {"model": f"{M}:block/north_star_lodestone"}}})
    w(A / "models/item/north_star_lodestone.json", {"parent": "minecraft:item/generated",
                                                    "textures": {"layer0": f"{M}:item/north_star_lodestone"}})
    loot_self("north_star_lodestone")
    w(A / "models/block/sky_window.json", {"textures": {"particle": f"{M}:block/sky_window"}})
    # 0.9.1: one-sided, the sky on the FACING face only (the renderer reads it; one model for all)
    w(A / "blockstates/sky_window.json", {"variants": {f"facing={f}": {"model": f"{M}:block/sky_window"}
                                                       for f in ("north", "south", "east", "west", "up", "down")}})
    w(A / "models/item/sky_window.json", {"parent": "minecraft:item/generated", "textures": {"layer0": f"{M}:item/sky_window"}})
    loot_self("sky_window", silk_only=False)
    w(A / "models/item/storm_crystal.json", {"parent": "minecraft:item/generated", "textures": {"layer0": f"{M}:item/storm_crystal"}})
    # charms: the dim bead by default, the lit one while the planet is up (item property wildskies:up)
    for c in CHARMS:
        w(A / f"models/item/{c}_charm_up.json", {"parent": "minecraft:item/generated",
                                                 "textures": {"layer0": f"{M}:item/{c}_charm"}})
        w(A / f"models/item/{c}_charm.json", {"parent": "minecraft:item/generated",
                                              "textures": {"layer0": f"{M}:item/{c}_charm_down"},
                                              "overrides": [{"predicate": {f"{M}:up": 1}, "model": f"{M}:item/{c}_charm_up"}]})
    # Curios (optional): the charms fit its charm slot, and players get one
    w(RES / "data/curios/tags/item/charm.json", {"replace": False, "values": [f"{M}:{c}_charm" for c in CHARMS]})
    w(D / "curios/entities/charm.json", {"entities": ["minecraft:player"], "slots": ["charm"]})


