def w(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2) + "\n", encoding="utf-8")


LANG = {}


def lang(k, v):
    LANG[k] = v


# ------------------------------------------------------------------------------------------------ simple blocks
SIMPLE = {  # id: (name, texture, render_type or None)
    "starstone": ("Starstone", "starstone", None),
    "starstone_bricks": ("Starstone Bricks", "starstone_bricks", None),
    "star_lamp": ("Star Lamp", "star_lamp", None),
    "nebula_glass": ("Nebula Glass", "nebula_glass", "minecraft:cutout"),
}


def simple_blocks():
    for bid, (name, tex, rt) in SIMPLE.items():
        if bid == "star_lamp":         # 1.1.0: a GeckoLib lamp, written by planet_pieces()
            lang(f"block.{M}.{bid}", name)
            continue
        if bid == "nebula_glass":      # 1.1.0: connected, its models and blockstate come from tools/nebula_glass_assets.py
            lang(f"block.{M}.{bid}", name)
            loot_self(bid)
            continue
        model = {"parent": "minecraft:block/cube_all", "textures": {"all": f"{M}:block/{tex}"}}
        if rt:
            model["render_type"] = rt
        w(A / f"models/block/{bid}.json", model)
        w(A / f"blockstates/{bid}.json", {"variants": {"": {"model": f"{M}:block/{bid}"}}})
        w(A / f"models/item/{bid}.json", {"parent": f"{M}:block/{bid}"})
        lang(f"block.{M}.{bid}", name)
        loot_self(bid)


def loot_self(bid, silk_only=False, alt=None):
    entry = {"type": "minecraft:item", "name": f"{M}:{bid}"}
    pool = {"rolls": 1, "entries": [entry], "conditions": [{"condition": "minecraft:survives_explosion"}]}
    if silk_only:
        pool["conditions"] = [SILK]
    pools = [pool]
    if alt:
        pools.append(alt)
    w(D / f"loot_table/blocks/{bid}.json", {"type": "minecraft:block", "pools": pools})


SILK = {"condition": "minecraft:match_tool", "predicate": {"predicates": {"minecraft:enchantments": [
    {"enchantments": "minecraft:silk_touch", "levels": {"min": 1}}]}}}
NO_SILK = {"condition": "minecraft:inverted", "term": SILK}


def other_blocks():
    # stardust: a glowing layer (carpet height), item is the block
    w(A / "models/block/stardust.json", {"parent": "minecraft:block/carpet", "textures": {"wool": f"{M}:block/stardust"}})
    w(A / "blockstates/stardust.json", {"variants": {"": {"model": f"{M}:block/stardust"}}})
    w(A / "models/item/stardust.json", {"parent": "minecraft:item/generated", "textures": {"layer0": f"{M}:item/stardust"}})
    lang(f"block.{M}.stardust", "Stardust")
    loot_self("stardust")


# ------------------------------------------------------------------------------------------------ telescope
def cube(frm, to, tex, faces=("north", "south", "east", "west", "up", "down"), rot=None, uv=None, front=None):
    e = {"from": frm, "to": to, "faces": {}}
    for f in faces:
        face = {"texture": "#" + (front if (front and f == "north") else tex)}
        if uv:
            face["uv"] = uv
        e["faces"][f] = face
    if rot:
        e["rotation"] = rot
    return e


def telescope_models():
    # 0.5.0: the telescope is drawn by GeckoLib (geo/block/telescope.geo.json, painted by tools/telescope/
    # make_telescope.py, draft A picked by the owner); the block model only gives the breaking particles.
    for t in range(3):
        old = A / f"models/block/telescope_{t}.json"
        if old.exists():
            old.unlink()
    w(A / "models/block/telescope.json", {"textures": {"particle": f"{M}:block/telescope_brass"}})
    variants = {f"facing={facing},tier={t}": {"model": f"{M}:block/telescope"}
                for facing in ("north", "east", "south", "west") for t in range(3)}
    w(A / "blockstates/telescope.json", {"variants": variants})
    w(A / "models/item/telescope.json", {"parent": "minecraft:item/generated", "textures": {"layer0": f"{M}:item/telescope"}})
    lang(f"block.{M}.telescope", "Telescope")
    w(D / "loot_table/blocks/telescope.json", {"type": "minecraft:block", "pools": [
        {"rolls": 1, "entries": [{"type": "minecraft:item", "name": f"{M}:telescope"}],
         "conditions": [{"condition": "minecraft:survives_explosion"}]},
        {"rolls": 1, "entries": [{"type": "minecraft:item", "name": f"{M}:star_lens"}],
         "conditions": [{"condition": "minecraft:block_state_property", "block": f"{M}:telescope",
                         "properties": {"tier": {"min": "1"}}}]},
        {"rolls": 1, "entries": [{"type": "minecraft:item", "name": f"{M}:nebula_filter"}],
         "conditions": [{"condition": "minecraft:block_state_property", "block": f"{M}:telescope",
                         "properties": {"tier": "2"}}]},
    ]})


